"""Prepare Inno's pinned download list and the small application-only payload.

Run from the repository root using the locked development environment.
Downloads here measure archive sizes; dependency archives are NOT bundled in Setup.
"""

import json
import subprocess
import tomllib
from pathlib import Path
from urllib.parse import unquote, urlsplit
from urllib.request import urlretrieve
from zipfile import ZipFile

from packaging.markers import Marker, default_environment
from packaging.tags import compatible_tags, cpython_tags
from packaging.utils import parse_wheel_filename

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
DOWNLOADS = BUILD / "installer-inputs"
GENERATED = ROOT / "packaging" / "generated"
DOWNLOADS.mkdir(parents=True, exist_ok=True)
GENERATED.mkdir(parents=True, exist_ok=True)
project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))[
    "project"
]
lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
packages = {package["name"]: package for package in lock["package"]}
environment = default_environment()
environment.update(
    python_version="3.12",
    python_full_version="3.12.10",
    sys_platform="win32",
    platform_system="Windows",
    platform_machine="AMD64",
)
tags = set(cpython_tags((3, 12), platforms=["win_amd64"]))
tags.update(compatible_tags((3, 12), interpreter="cp312", platforms=["win_amd64"]))
required = set()


def collect(name):
    if name in required:
        return
    required.add(name)
    package = packages[name]
    if "dependencies" in package:
        for dependency in package["dependencies"]:
            if "marker" not in dependency or Marker(dependency["marker"]).evaluate(
                environment
            ):
                collect(dependency["name"])


collect(project["name"])
required.remove(project["name"])
payloads = json.loads(
    (ROOT / "packaging/runtime-sources.json").read_text(encoding="utf-8")
)
for name in sorted(required):
    wheel = next(
        wheel
        for wheel in packages[name]["wheels"]
        if parse_wheel_filename(unquote(Path(urlsplit(wheel["url"]).path).name))[3]
        & tags
    )
    payloads.append(
        {
            "name": unquote(Path(urlsplit(wheel["url"]).path).name),
            "url": wheel["url"],
            "sha256": wheel["hash"].removeprefix("sha256:"),
            "destination": "runtime\\Lib\\site-packages",
        }
    )

entries = [
    "; Generated by packaging/prepare.py from uv.lock and runtime-sources.json.",
    "[Files]",
]
for payload in payloads:
    path = DOWNLOADS / payload["name"]
    print(f"Measuring {payload['name']}", flush=True)
    urlretrieve(payload["url"], path)
    with ZipFile(path) as archive:
        payload["extracted_size"] = sum(item.file_size for item in archive.infolist())
    payload["download_size"] = path.stat().st_size
    # Wheels use ZIP format. DestName selects Inno's native ZIP extractor.
    archive_name = Path(payload["name"]).stem + ".zip"
    entries.append(
        f'Source: "{payload["url"]}"; DestDir: "{{app}}\\{payload["destination"]}"; '
        f'DestName: "{archive_name}"; ExternalSize: {payload["extracted_size"]}; '
        f'Hash: "{payload["sha256"]}"; '
        "Flags: external download extractarchive ignoreversion recursesubdirs createallsubdirs"
    )

(GENERATED / "downloads.iss").write_text("\n".join(entries) + "\n", encoding="utf-8")
(GENERATED / "payloads.json").write_text(
    json.dumps(payloads, indent=2) + "\n", encoding="utf-8"
)
(GENERATED / "version.iss").write_text(
    f'#define AppVersion "{project["version"]}"\n', encoding="utf-8"
)
subprocess.run(
    ["uv", "build", "--wheel", "--out-dir", str(BUILD / "wheel")], cwd=ROOT, check=True
)
with ZipFile(
    BUILD / "wheel" / f"marketmaker-{project['version']}-py3-none-any.whl"
) as archive:
    archive.extractall(BUILD / f"app-{project['version']}")
print(
    f"Prepared {len(payloads)} downloads: {sum(p['download_size'] for p in payloads):,} bytes"
)
